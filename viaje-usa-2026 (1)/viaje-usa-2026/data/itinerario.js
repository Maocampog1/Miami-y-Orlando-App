export function mapsLink(lugar) {
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(lugar)}`;
}

export function rutaLink(paradas) {
  if (!paradas || paradas.length < 2) return null;
  const origin = encodeURIComponent(paradas[0]);
  const destination = encodeURIComponent(paradas[paradas.length - 1]);
  const waypoints = paradas.slice(1, -1).map(encodeURIComponent).join("%7C");
  let url = `https://www.google.com/maps/dir/?api=1&origin=${origin}&destination=${destination}`;
  if (waypoints) url += `&waypoints=${waypoints}`;
  return url;
}
